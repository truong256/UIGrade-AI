class JoinClassroomUseCase @Inject constructor(
    private val repository: ClassroomRepository,
    private val authRepository: AuthRepository
) {
    suspend operator fun invoke(joinCode: String): Result<ClassMembership> {
        val code = joinCode.trim().uppercase()
        if (code.isBlank()) return Result.failure(IllegalArgumentException("Mã tham gia không hợp lệ"))

        val user = authRepository.getCurrentUser()
            ?: return Result.failure(IllegalArgumentException("Bạn chưa đăng nhập"))

        if (user.role != UserRole.STUDENT)
            return Result.failure(IllegalArgumentException("Chỉ sinh viên mới có thể tham gia lớp học"))

        return repository.joinClassroom(code, user.id)
    }
}

