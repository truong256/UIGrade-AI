class RespondToJoinRequestUseCase @Inject constructor(
    private val repository: ClassroomRepository,
    private val authRepository: AuthRepository
) {
    suspend operator fun invoke(classroomId: String, requestId: String, approve: Boolean): Result<JoinRequest> =
        requireOwner(classroomId, repository, authRepository).fold(
            onSuccess = { repository.respondToJoinRequest(requestId, approve) },
            onFailure = { Result.failure(it) }
        )
}

private suspend fun requireOwner(
    classroomId: String,
    repository: ClassroomRepository,
    authRepository: AuthRepository
): Result<Classroom> {
    val user = authRepository.getCurrentUser()
        ?: return Result.failure(IllegalArgumentException("Bạn chưa đăng nhập"))
    if (user.role != UserRole.LECTURER) {
        return Result.failure(IllegalArgumentException("Chỉ giảng viên mới có quyền thực hiện thao tác này"))
    }
    val classroom = repository.getClassroomById(classroomId)
        ?: return Result.failure(IllegalArgumentException("Không tìm thấy lớp học"))
    if (classroom.lecturerId != user.id) {
        return Result.failure(IllegalArgumentException("Bạn không có quyền thay đổi lớp học này"))
    }
    return Result.success(classroom)
}
