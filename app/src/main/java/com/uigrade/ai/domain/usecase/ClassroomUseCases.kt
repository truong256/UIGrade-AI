class JoinClassroomUseCase @Inject constructor(
    private val repository: ClassroomRepository,
    private val authRepository: AuthRepository
) {
    suspend operator fun invoke(joinCode: String): Result<ClassMembership> {
        val code = joinCode.trim().uppercase()
        if (code.isBlank()) return Result.failure(IllegalArgumentException("Mã tham gia không hợp lệ"))

        val user = authRepository.getCurrentUser()
            ?: return Result.failure(IllegalArgumentException("Bạn chưa đăng nhập"))

        if (user.role != UserRole.STUDENT)
            return Result.failure(IllegalArgumentException("Chỉ sinh viên mới có thể tham gia lớp học"))

        return repository.joinClassroom(code, user.id)
    }
}

class GetClassroomStudentsUseCase @Inject constructor(
    private val repository: ClassroomRepository
) {
    suspend operator fun invoke(classroomId: String): List<User> =
        repository.getStudentsInClassroom(classroomId)
}

class RegenerateJoinCodeUseCase @Inject constructor(
    private val repository: ClassroomRepository,
    private val authRepository: AuthRepository
) {
    suspend operator fun invoke(classroomId: String): Result<String> {
        val user = authRepository.getCurrentUser()
            ?: return Result.failure(IllegalArgumentException("Bạn chưa đăng nhập"))
        val classroom = repository.getClassroomById(classroomId)
            ?: return Result.failure(IllegalArgumentException("Không tìm thấy lớp học"))
        if (classroom.lecturerId != user.id)
            return Result.failure(IllegalArgumentException("Bạn không có quyền thay đổi lớp học này"))
        return repository.regenerateJoinCode(classroomId)
    }
}

class ArchiveClassroomUseCase @Inject constructor(
    private val repository: ClassroomRepository,
    private val authRepository: AuthRepository
) {
    suspend operator fun invoke(classroomId: String): Result<Unit> {
        val user = authRepository.getCurrentUser()
            ?: return Result.failure(IllegalArgumentException("Bạn chưa đăng nhập"))
        val classroom = repository.getClassroomById(classroomId)
            ?: return Result.failure(IllegalArgumentException("Không tìm thấy lớp học"))
        if (classroom.lecturerId != user.id)
            return Result.failure(IllegalArgumentException("Bạn không có quyền lưu trữ lớp học này"))
        return repository.archiveClassroom(classroomId)
    }
}

