package com.uigrade.ai.ui.components.mascot

/**
 * Poses and emotional states of the UIGrade AI Cat Mascot.
 */
enum class CatMascotPose {
    /** Welcoming user on Get Started screen with waving paw and gentle smile */
    WELCOME,

    /** Guiding user through input fields with focused, helpful posture */
    GUIDE,

    /** Cheering user on successful validation, signup, or login */
    SUCCESS,

    /** Thinking or verifying input */
    THINKING
}
